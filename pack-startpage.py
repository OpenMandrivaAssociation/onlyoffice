#!/usr/bin/python
# Build the desktop start page with upstream grunt, then archive the result.
#
# DesktopEditors loads <install>/index.html. Upstream produces that file,
# and deploy/noconnect.html, with loginpage/build/Gruntfile.js (svg sprites,
# spritesmith, less, terser, concat, inline). The grunt plugins are npm
# packages. Builders have no network, so this script is the maintainer step:
# npm ci, grunt, then loginpage-deploy.tar.gz. The rpm unpacks that archive
# and does not run grunt.
#
# nodejs-grunt is grunt 1.6.1, the version the Gruntfile locks. The cooker
# rpm ships neither /usr/bin/grunt nor grunt's own modules, so a grunt on
# PATH is used when `grunt --version` works, and otherwise the grunt 1.6.1
# installed next to the Gruntfile.
#
# --templates-only skips grunt and only writes the blank docx/xlsx/pptx
# files CreateLocalFile converts. Those are not grunt output. A wipe of
# desktop-apps removes deploy/; run this script again.

import os
import shutil
import subprocess
import sys
import tarfile
import zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
LOGIN = os.path.join(ROOT, "desktop-apps", "common", "loginpage")
BUILD = os.path.join(LOGIN, "build")
DEPLOY = os.path.join(LOGIN, "deploy")

# Direct dependencies of loginpage/build/package.json, plus the sprite
# package it pulls in through the file:sprites link.
PLUGIN_DIRS = (
    "grunt",
    "grunt-contrib-clean",
    "grunt-contrib-concat",
    "grunt-contrib-copy",
    "grunt-contrib-htmlmin",
    "grunt-contrib-less",
    "grunt-inline",
    "grunt-spritesmith",
    "grunt-svg-sprite",
    "grunt-terser",
    "grunt-text-replace",
    "lodash",
    "terser",
)


def ensure_npm():
    modules = os.path.join(BUILD, "node_modules")
    if all(os.path.isdir(os.path.join(modules, name)) for name in PLUGIN_DIRS):
        return
    print("installing loginpage npm dependencies")
    # npm is often configured offline. This fetch is the maintainer step.
    # The rpm build never reaches it.
    subprocess.check_call(
        ["npm", "ci", "--offline=false", "--no-audit", "--no-fund"],
        cwd=BUILD,
    )


def grunt_argv():
    system = shutil.which("grunt")
    if system:
        probe = subprocess.run(
            [system, "--version"],
            cwd=BUILD,
            capture_output=True,
            text=True,
        )
        text = probe.stdout + probe.stderr
        if probe.returncode == 0 and "grunt v" in text:
            return [system]
    local = os.path.join(BUILD, "node_modules", ".bin", "grunt")
    if os.path.isfile(local) and os.access(local, os.X_OK):
        return [local]
    raise SystemExit("grunt is not runnable (nodejs-grunt, or npm ci in %s)" % BUILD)


def run_grunt():
    ensure_npm()
    argv = grunt_argv()
    print("running %s" % " ".join(argv))
    subprocess.check_call(argv, cwd=BUILD)
    for name in ("index.html", "noconnect.html"):
        path = os.path.join(DEPLOY, name)
        if not os.path.isfile(path) or os.path.getsize(path) < 1000:
            raise SystemExit("grunt did not write %s" % path)


def result_files():
    names = ["deploy/index.html", "deploy/noconnect.html"]
    generated = os.path.join(LOGIN, "res", "img", "generated")
    for name in sorted(os.listdir(generated)):
        if os.path.isfile(os.path.join(generated, name)):
            names.append("res/img/generated/" + name)
    css = os.path.join(LOGIN, "src", "css")
    for name in sorted(os.listdir(css)):
        if name.startswith("toolicons") and name.endswith(".less"):
            names.append("src/css/" + name)
    missing = [name for name in names if not os.path.isfile(os.path.join(LOGIN, name))]
    if missing:
        raise SystemExit("grunt result missing: %s" % ", ".join(missing))
    return names


def write_tar(path):
    parent = os.path.dirname(os.path.abspath(path))
    if parent:
        os.makedirs(parent, exist_ok=True)
    with tarfile.open(path, "w:gz") as archive:
        for name in result_files():
            archive.add(os.path.join(LOGIN, name), arcname=name, recursive=False)
    print("wrote %s" % path)



def write_zip(path, parts):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, body in parts.items():
            text = body.strip() + "\n"
            archive.writestr(name, text)


